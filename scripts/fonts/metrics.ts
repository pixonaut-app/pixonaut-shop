/**
 * The metrics table a typeface's fallback face is measured from: for every
 * family in the metrics collection (the Google Fonts catalogue the Font
 * Library installs from, and the system fonts a fallback is drawn in), its
 * units per em, ascent, descent and line gap, and the average width of Latin
 * text at each weight it comes in. `inc/Fonts/` turns it into the
 * `size-adjust` and line-metric overrides of a store's fonts.
 */

/** One face's metrics as the collection gives them. */
export type FaceMetrics = {
	familyName: string;
	category?: string;
	ascent: number;
	descent: number;
	lineGap: number;
	unitsPerEm: number;
	xWidthAvg: number;
	subsets?: { latin?: { xWidthAvg: number } };
	variants?: Record< string, FaceMetrics >;
};

/** A family's row: whether it is serif, then its vertical metrics and its widths by weight. */
export type MetricsRow = {
	serif: boolean;
	unitsPerEm: number;
	ascent: number;
	descent: number;
	lineGap: number;
	widths: Record< number, number >;
};

/** The weight the collection's base entry is: its regular face. */
const REGULAR_WEIGHT = 400;

/** A variant key that is a weight alone, so neither `regular` nor an italic. */
const UPRIGHT_WEIGHT = /^\d+$/;

function latinWidth( face: FaceMetrics ): number {
	return face.subsets?.latin?.xWidthAvg ?? face.xWidthAvg;
}

/**
 * One row per family, keyed by its name in lower case so a store's family
 * name finds it whatever its casing. The vertical metrics are the regular
 * face's: nearly every family keeps them across its weights.
 */
export function metricsTable(
	collection: Record< string, FaceMetrics >,
): Record< string, MetricsRow > {
	const table: Record< string, MetricsRow > = {};

	for ( const family of Object.values( collection ) ) {
		const widths: Record< number, number > = { [ REGULAR_WEIGHT ]: latinWidth( family ) };

		for ( const [ key, variant ] of Object.entries( family.variants ?? {} ) ) {
			if ( UPRIGHT_WEIGHT.test( key ) ) {
				widths[ Number( key ) ] = latinWidth( variant );
			}
		}

		table[ family.familyName.toLowerCase() ] = {
			serif: family.category === 'serif',
			unitsPerEm: family.unitsPerEm,
			ascent: family.ascent,
			descent: Math.abs( family.descent ),
			lineGap: family.lineGap,
			widths,
		};
	}

	return table;
}

function phpString( value: string ): string {
	return `'${ value.replace( /\\/g, '\\\\' ).replace( /'/g, "\\'" ) }'`;
}

/**
 * The table as a PHP file returning an array, one family a line:
 * `'name' => [serif, unitsPerEm, ascent, descent, lineGap, [weight => width]]`.
 */
export function metricsPhp( table: Record< string, MetricsRow > ): string {
	const lines = Object.keys( table )
		.sort()
		.map( ( name ) => {
			const row = table[ name ];
			const widths = Object.entries( row.widths )
				.map( ( [ weight, width ] ) => `${ weight } => ${ width }` )
				.join( ', ' );
			return `    ${ phpString( name ) } => [${ row.serif ? 'true' : 'false' }, ${ row.unitsPerEm }, ${ row.ascent }, ${ row.descent }, ${ row.lineGap }, [${ widths }]],`;
		} );

	return [
		'<?php',
		'',
		'// Generated by `pnpm fonts:metrics` from @capsizecss/metrics (MIT). Do not edit.',
		'',
		'return [',
		...lines,
		'];',
		'',
	].join( '\n' );
}
